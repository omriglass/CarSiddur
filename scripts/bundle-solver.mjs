#!/usr/bin/env node
// scripts/bundle-solver.mjs
//
// Bundles the pure `src/solver` package (CLAUDE.md hard rule 5: no DOM, no
// Supabase, no external imports) into a single dependency-free ESM file at
// `supabase/functions/_shared/solver.js` so Edge Functions — which only ever
// deploy files under `supabase/functions` (ARCHITECTURE.md §4) — can import
// the exact same solver the browser runs. Also emits a best-effort
// `solver.d.ts` (optional; failures there never fail the bundle).
//
// Usage: `npm run functions:bundle` (also runs the Node smoke test at
// supabase/tests/bundle_solver.test.mjs). Regenerate after any change under
// `src/solver`. Never hand-edit the generated output (CLAUDE.md hard rule 8).

import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const entry = join(root, 'src/solver/index.ts');
const outDir = join(root, 'supabase/functions/_shared');
const outfile = join(outDir, 'solver.js');
const dtsOutfile = join(outDir, 'solver.d.ts');

const GENERATED_BANNER = [
  '// GENERATED by scripts/bundle-solver.mjs from src/solver — do not hand-edit (CLAUDE.md hard rule 8).',
  '// Regenerate with `npm run functions:bundle` after any change under src/solver.',
].join('\n');

async function bundleJs() {
  mkdirSync(outDir, { recursive: true });
  const result = await build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    sourcemap: false,
    legalComments: 'none',
    banner: { js: GENERATED_BANNER },
    metafile: true,
    logLevel: 'silent',
  });

  // Fail loudly if the bundle ever pulls in a package from node_modules —
  // the solver must stay dependency-free so the Edge Function bundle needs
  // no `npm:`/`deno.land` imports for it (SOLVER.md, CLAUDE.md hard rule 5).
  const externalInputs = Object.keys(result.metafile.inputs).filter((p) => p.includes('node_modules'));
  if (externalInputs.length > 0) {
    throw new Error(
      `bundle-solver: src/solver must have no external imports, but the bundle pulled in:\n${externalInputs.join('\n')}`,
    );
  }

  const size = readFileSync(outfile).byteLength;
  console.log(`[bundle-solver] wrote ${outfile} (${(size / 1024).toFixed(1)} KiB, ${Object.keys(result.metafile.inputs).length} modules)`);
}

/** Recursively deletes stale generated *.d.ts files under `dir` (from a previous run whose
 *  src/solver file layout has since changed), without touching hand-written files like cors.ts. */
function removeStaleDts(dir) {
  if (!existsSync(dir)) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      removeStaleDts(full);
      if (readdirSync(full).length === 0) rmSync(full, { recursive: true, force: true });
    } else if (entry.name.endsWith('.d.ts')) {
      rmSync(full, { force: true });
    }
  }
}

// tsc mirrors src/solver's own module graph (types.ts, seatFit.ts, live.ts, rules/*.ts, ...),
// so a single bundled index.d.ts is not self-contained — esbuild bundles JS, but there is no
// project dependency that bundles .d.ts files the same way. Instead, the whole declaration
// tree is copied next to solver.js (this is still one `import ... from './solver.d.ts'` for
// callers; the sibling files are an implementation detail, same idea as a `.js` + `.js.map`
// pair). Best-effort only (task: "+ .d.ts optional") — never fails the JS bundle step.
function bundleDts() {
  const tmpTsconfig = join(here, '.solver-dts.tsconfig.json');
  const tmpOutDir = join(root, '.tmp-solver-dts');
  const tsconfig = {
    compilerOptions: {
      target: 'ES2022',
      module: 'ESNext',
      moduleResolution: 'Bundler',
      lib: ['ES2022'],
      strict: true,
      declaration: true,
      emitDeclarationOnly: true,
      skipLibCheck: true,
      noEmitOnError: false,
      outDir: tmpOutDir,
      rootDir: join(root, 'src/solver'),
      types: [],
    },
    include: ['../src/solver/**/*.ts'],
    exclude: ['../src/solver/**/__tests__/**', '../src/solver/**/__fixtures__/**'],
  };

  try {
    writeFileSync(tmpTsconfig, JSON.stringify(tsconfig, null, 2));
    const tscBin = join(root, 'node_modules/typescript/bin/tsc');
    if (!existsSync(tscBin)) {
      console.warn('[bundle-solver] typescript not found; skipping solver.d.ts');
      return;
    }
    execFileSync(process.execPath, [tscBin, '--project', tmpTsconfig], { stdio: 'pipe' });

    const generatedIndex = join(tmpOutDir, 'index.d.ts');
    if (!existsSync(generatedIndex)) {
      console.warn('[bundle-solver] tsc produced no index.d.ts; skipping solver.d.ts');
      return;
    }

    removeStaleDts(outDir);
    cpSync(tmpOutDir, outDir, { recursive: true });
    renameSync(join(outDir, 'index.d.ts'), dtsOutfile);
    const withBanner = [GENERATED_BANNER, readFileSync(dtsOutfile, 'utf8')].join('\n');
    writeFileSync(dtsOutfile, withBanner);
    console.log(`[bundle-solver] wrote ${dtsOutfile} (+ its sibling .d.ts files under _shared/)`);
  } catch (err) {
    // Best-effort only (task: "+ .d.ts optional") — never fail the bundle
    // step over declaration-emit trouble (e.g. a solver file that only
    // typechecks in the app tsconfig's DOM lib).
    console.warn('[bundle-solver] solver.d.ts generation skipped:', err.message.split('\n')[0]);
  } finally {
    rmSync(tmpTsconfig, { force: true });
    rmSync(tmpOutDir, { recursive: true, force: true });
  }
}

await bundleJs();
bundleDts();
